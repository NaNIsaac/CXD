"""Write a synthetic rocking scan for the README and the notebooks.

Nothing here is measured data. The 3D pattern is a Gaussian Bragg peak with
three pairs of streaks along fixed directions, sampled with Poisson noise:

    synthetic.spec      SPEC file with one rocking scan (#S 1): Theta, imroi1
    S0001/*.tif         one uint16 256x256 Timepix-sized frame per Theta step
    scan_0001.mat       the 64x64 ROI around the peak, 'data' as (y, x, frame)

Usage::

    python examples/synthetic_scan.py [OUT_DIR]   # default: examples/data
"""

import sys
from pathlib import Path

import numpy as np
import tifffile
from scipy.io import savemat

N_FRAMES = 48
DET = 256  # detector side [px]
ROI = 64  # ROI side [px], centred on the detector
THETA0 = 30.0  # deg, Bragg angle of the synthetic reflection
THETA_STEP = 0.01  # deg per frame
SDD = 1000.0  # mm
STREAKS = np.array([[0.3, 0.0, 1.0], [0.3, 1.0, 0.2], [1.0, -0.3, 0.4]])  # (frame, y, x)


def make_volume(seed: int = 0) -> np.ndarray:
    """(frame, y, x) counts in the ROI: central peak + streaks, Poisson sampled."""
    c = np.array([N_FRAMES, ROI, ROI]) / 2
    r = np.stack(np.indices((N_FRAMES, ROI, ROI)), axis=-1) - c
    vol = 5000.0 * np.exp(-(r**2).sum(-1) / (2 * 2.0**2))
    for d in STREAKS / np.linalg.norm(STREAKS, axis=1, keepdims=True):
        t = r @ d
        perp2 = (r**2).sum(-1) - t**2
        vol += 50.0 * np.exp(-perp2 / (2 * 1.0**2)) * np.exp(-np.abs(t) / 15.0)
    return np.random.default_rng(seed).poisson(vol + 0.05).astype(np.uint16)


def spec_text(thetas: np.ndarray, counts: np.ndarray) -> str:
    lo = (DET - ROI) // 2
    rows = "\n".join(f"{t:.4f} {c:d}" for t, c in zip(thetas, counts, strict=True))
    return f"""\
#F synthetic.spec
#E 1700000000
#D Mon Jan 01 00:00:00 2024
#C synthetic example generated by examples/synthetic_scan.py, not measured data

#O0 Theta Delta Gamma Chi

#S 1 rscan Theta {thetas[0]:.4f} {thetas[-1]:.4f} {len(thetas) - 1} 1
#D Mon Jan 01 00:00:00 2024
#P0 {THETA0:.4f} {2 * THETA0:.4f} 0.0 0.0
#UXML <ad_detector><sample_detector_distance>{SDD}</sample_detector_distance></ad_detector>
#UXML <ad_regions_of_interest><roi><name>imroi1</name><min_x>{lo}</min_x><size_x>{ROI}</size_x><min_y>{lo}</min_y><size_y>{ROI}</size_y></roi></ad_regions_of_interest>
#N 2
#L Theta imroi1
{rows}
"""


def main(out_dir: Path) -> None:
    roi = make_volume()
    thetas = THETA0 + THETA_STEP * (np.arange(N_FRAMES) - N_FRAMES // 2)

    tif_dir = out_dir / "S0001"
    tif_dir.mkdir(parents=True, exist_ok=True)
    lo = (DET - ROI) // 2
    for i, frame in enumerate(roi):
        full = np.zeros((DET, DET), np.uint16)
        full[lo : lo + ROI, lo : lo + ROI] = frame
        tifffile.imwrite(tif_dir / f"S0001_{i:05d}.tif", full)

    savemat(out_dir / "scan_0001.mat", {"data": roi.transpose(1, 2, 0), "synthetic": True})
    counts = roi.reshape(N_FRAMES, -1).sum(axis=1)
    (out_dir / "synthetic.spec").write_text(spec_text(thetas, counts), encoding="utf-8")
    print(f"wrote synthetic.spec, S0001/ ({N_FRAMES} frames), scan_0001.mat to {out_dir}")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).parent / "data")
